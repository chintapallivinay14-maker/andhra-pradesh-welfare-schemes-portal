def main():
    db = SessionLocal()
    added = 0
    skipped = 0

    try:
        existing_names = {
            name.strip().casefold()
            for (name,) in db.query(Scheme.name).all()
            if name
        }

        for item in AP_SCHEMES:
            key = item["name"].strip().casefold()

            if key in existing_names:
                print(f"SKIPPED (already exists): {item['name']}")
                skipped += 1
                continue

            # Keep new records pending verification until the full details
            # have been checked against the current official notification.
            scheme = Scheme(
                **item,
                verification_status="Needs Verification",
                is_active=True,
            )
            db.add(scheme)
            existing_names.add(key)
            added += 1
            print(f"ADDED: {item['name']}")

        db.commit()
        print("\nImport completed.")
        print(f"Added: {added}")
        print(f"Skipped existing: {skipped}")
        print(f"Total schemes in database: {db.query(Scheme).count()}")

    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()